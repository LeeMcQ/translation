const REPAIRS = [
  [/\bseel\b/gi, "seël"],
  [/\bluykseode\b/gi, "Laodisea"],
  [/\bgoeie more\b/gi, "Goeiemôre"],
  [/\bgoeiembore\b/gi, "Goeiemôre"],
];

export function applyGlossaryAf(text) {
  let out = text;
  for (const [re, to] of REPAIRS) out = out.replace(re, to);
  return out;
}

export function pinEnglishTerms(translated, sourceAf) {
  let out = translated || "";
  const sundayLaw = /sondagwet|sunday law/i.test(sourceAf);
  if (/\bsabbat/i.test(sourceAf) && !sundayLaw) {
    out = out.replace(/\bSaturdays?\b/gi, "Sabbath");
    out = out.replace(/\bSundays?\b/gi, "Sabbath");
  }
  if (/\bseël|\bseel/i.test(sourceAf)) {
    out = out.replace(/\b(stamp|sealant|wax seal|sealskin)\b/gi, "seal");
  }
  if (/\boorblyfsel/i.test(sourceAf)) {
    out = out.replace(/\b(leftover|remainder|residue)s?\b/gi, "remnant");
  }
  if (/\bheiligdom/i.test(sourceAf)) {
    out = out.replace(/\b(shrine|holy place)\b/gi, "sanctuary");
  }
  if (/\bwederkoms|tweede koms/i.test(sourceAf)) {
    out = out.replace(/\b(return|coming back|reappearance)\b/gi, "second coming");
  }
  const sorted = [...GLOSSARY].sort((a, b) => b.af.length - a.af.length);
  for (const row of sorted) {
    const inSrc = new RegExp(`\\b${escapeRe(row.af)}\\b`, "i").test(sourceAf);
    if (!inSrc) continue;
    const stillAf = new RegExp(`\\b${escapeRe(row.af)}\\b`, "gi");
    out = out.replace(stillAf, row.en);
  }
  return out;
}

export function searchGlossary(q, pool = GLOSSARY) {
  const n = (q || "").trim().toLowerCase();
  if (!n) return pool;
  return pool.filter(
    (r) =>
      r.af.toLowerCase().includes(n) ||
      r.en.toLowerCase().includes(n) ||
      (r.note || "").toLowerCase().includes(n) ||
      (r.cat || "").toLowerCase().includes(n),
  );
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
