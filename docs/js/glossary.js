export function applyGlossaryAf(text) {
  let out = text;
  const sorted = [...GLOSSARY].sort((a, b) => b.af.length - a.af.length);
  for (const row of sorted) {
    const re = new RegExp(`\\b${escapeRe(row.af)}\\b`, "gi");
    out = out.replace(re, row.af);
  }
  return out.replace(/\bseel\b/gi, "seël");
}

export function pinEnglishTerms(translated, sourceAf) {
  let out = translated;
  const sorted = [...GLOSSARY].sort((a, b) => b.af.length - a.af.length);
  for (const row of sorted) {
    if (new RegExp(`\\b${escapeRe(row.af)}\\b`, "i").test(sourceAf)) {
      const wrongStamps = /\b(stamp|sealant|sealskin|wax seal)\b/gi;
      if (/seël|seel|seël/i.test(row.af)) {
        out = out.replace(wrongStamps, "seal");
      }
      const loose = new RegExp(`\\b${escapeRe(row.en)}\\b`, "i");
      if (!loose.test(out) && row.en.split(" ").length <= 4) {
        // leave machine text; pinning happens via phrase bank more reliably
      }
    }
  }
  return out;
}

export function searchGlossary(q, pool = GLOSSARY) {
  const n = q.trim().toLowerCase();
  if (!n) return pool;
  return pool.filter(
    (r) =>
      r.af.toLowerCase().includes(n) ||
      r.en.toLowerCase().includes(n) ||
      (r.note || "").toLowerCase().includes(n) ||
      (r.cat || "").toLowerCase().includes(n),
  );
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
