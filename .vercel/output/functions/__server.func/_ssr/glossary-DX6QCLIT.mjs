function repairSpeech(text) {
	let out = text.replace(/\s+/g, " ").trim();
	for (const [re, to] of STT_REPAIRS) out = out.replace(re, to);
	return out;
}
function norm(s) {
	return s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^\p{L}\p{N}\s]/gu, "").replace(/\s+/g, " ").trim();
}
function lookupLiturgy(text) {
	const key = norm(text);
	for (const [af, en] of LITURGY) if (norm(af) === key) return en;
	return null;
}
function phraseRe(term) {
	const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+");
	return new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, "giu");
}
function applyPairs(text, pairs) {
	const sorted = [...pairs].sort((a, b) => b.af.length - a.af.length);
	let out = text;
	for (const { af, en } of sorted) {
		if (af.length < 2) continue;
		out = out.replace(phraseRe(af), en);
	}
	return out;
}
/** Zero-cost backup: liturgy, Kaaps, then everyday pulpit Afrikaans. */
function lexiconTranslate(text) {
	let out = applyPairs(text, LITURGY.map(([af, en]) => ({
		af,
		en
	})));
	out = applyPairs(out, SLANG.filter((s) => !s.promptOnly));
	out = applyPairs(out, LEXICON.map(([af, en]) => ({
		af,
		en
	})));
	out = out.replace(/'n\s+/g, "a ").replace(/\s+/g, " ").trim();
	return out;
}
