var BOOK_ALT = BOOKS.map(([af]) => af.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).sort((a, b) => b.length - a.length).join("|");
var REF_RE = new RegExp(`\\b(${BOOK_ALT})\\s+(\\d{1,3})(?:\\s*(?::|vers)\\s*(\\d{1,3})(?:\\s*[–-]\\s*(\\d{1,3}))?)?`, "gi");
function scriptureNote(text) {
	const hits = [];
	const re = new RegExp(REF_RE.source, "gi");
	let m;
	while (m = re.exec(text)) {
		const book = BOOKS.find((b) => b[0].toLowerCase() === m[1].toLowerCase())?.[1] ?? m[1];
		const ref = m[3] ? m[4] ? `${book} ${m[2]}:${m[3]}–${m[4]}` : `${book} ${m[2]}:${m[3]}` : `${book} ${m[2]}`;
		hits.push(ref);
	}
	if (!hits.length) return null;
	return `Open ${hits.join(" · ")} in your own Bible — we do not invent Scripture.`;
}
function isScriptureReading(text) {
	if (!scriptureNote(text)) return false;
	if (/^(lees saam|ons lees|die skrif|skriflesing|die lesing)/i.test(text.trim())) return true;
	return text.trim().split(/\s+/).length >= 18;
}
